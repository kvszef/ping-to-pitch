// Month names as the engine (engine/format.ts) and data/facts.ts write them, long and short.
export const MONTH_EN: Record<string, string> = {
  Januar: 'January', 'Jan.': 'Jan', Februar: 'February', 'Feb.': 'Feb', März: 'March', April: 'April', 'Apr.': 'Apr',
  Mai: 'May', Juni: 'June', Juli: 'July', August: 'August', 'Aug.': 'Aug', September: 'September', 'Sept.': 'Sep',
  Oktober: 'October', 'Okt.': 'Oct', November: 'November', 'Nov.': 'Nov', Dezember: 'December', 'Dez.': 'Dec',
}

// Fixed wording around a number, a date or a name: composed at runtime, so not a plain map entry.
const PATTERNS: [RegExp, (m: RegExpExecArray) => string][] = [
  [/^(\S+) (\d{4})$/, (m) => (MONTH_EN[m[1]] ? `${MONTH_EN[m[1]]} ${m[2]}` : '')],
  [/^(\d+) Fehler · (\d+) Warnung(?:en)?$/, (m) => `${m[1]} error${m[1] === '1' ? '' : 's'} · ${m[2]} warning${m[2] === '1' ? '' : 's'}`],
  [/^(\d+) Fehler, (\d+) Warnung(?:en)?$/, (m) => `${m[1]} error${m[1] === '1' ? '' : 's'}, ${m[2]} warning${m[2] === '1' ? '' : 's'}`],
  [/^(\d+) offene Regelverletzung(?:en)?$/, (m) => `${m[1]} open rule violation${m[1] === '1' ? '' : 's'}`],
  [/^(\d+) Jahre$/, (m) => `${m[1]} years`],
  [/^(\d+), davon (\d+) Fremddepot \(ex-custody\)$/, (m) => `${m[1]}, of which ${m[2]} external custody (ex-custody)`],
  [/^in (\d+) Portfolios$/, (m) => `in ${m[1]} portfolios`],
  [/^([A-Z]{3}), inkl\. Fremddepot ([\d']+)$/, (m) => `${m[1]}, incl. external custody ${m[2]}`],
  [/^(\d+) Kunden? geladen$/, (m) => `${m[1]} client${m[1] === '1' ? '' : 's'} loaded`],
  [/^Eintrag (\d+) hat keine Kundennummer \(ClientRef\)\.$/, (m) => `Entry ${m[1]} has no client number (ClientRef).`],
  [/^Nachfragen zu (.+) …( {2}\/)?$/, (m) => `Ask about ${m[1]} …${m[2] ?? ''}`],
  [/^Frage zu (.+) …$/, (m) => `Question about ${m[1]} …`],
  [/^Fehler (\d+)$/, (m) => `Error ${m[1]}`],
  [/^Stand (\d{2}\.\d{2}\.\d{4})$/, (m) => `As of ${m[1]}`],
  [/^Wertverlauf, Stand (.+)$/, (m) => `Value history, as of ${m[1]}`],
  [/^Grösste von (\d+) Positionen$/, (m) => `Largest of ${m[1]} positions`],
]

/** The hand-written English for a German UI string, or undefined when it is not a fixed one. */
export function staticEn(text: string): string | undefined {
  const hit = STATIC_EN[text]
  if (hit !== undefined) return hit
  for (const [re, write] of PATTERNS) {
    const m = re.exec(text)
    if (m) { const out = write(m); if (out) return out }
  }
  return undefined
}

/** A fixed label in the display language, synchronously: for components that need no model fallback. */
export const tr = (text: string, language: 'de' | 'en'): string => (language === 'de' ? text : staticEn(text) ?? text)
